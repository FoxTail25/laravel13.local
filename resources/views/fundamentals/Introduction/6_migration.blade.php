    <x-page.page-text>
        Когда Laravel подключается к базе данных, ему нужны таблицы: для пользователей, сессий, очередей и других
        служебных данных. Создавать их вручную через PMA (PhpMyAdmin) или другой инструмент неудобно. Для этого в
        Laravel есть миграции.
        <br />
        Миграции - это PHP файлы в папке <code>database/migrations/</code>. В каждом файле описано, какие таблицы
        создать или как изменить уже существующие. При установке Laravel уже кладёт в проект несколько таких файлов с
        начальной структурой базы.
        <br />
        Чтобы применить миграции и создать таблицы в базе, выполните команду:
        <br />
        <code>php artisan migrate</code>
        <br />
        Laravel прочитает файлы из <code>database/migrations/</code> и создаст нужные таблицы. Если вы переключитесь с
        SQLite на MySQL, MariaDB или PostgreSQL, миграции нужно будет запустить заново - в новой базе таблиц ещё нет.
        <br />
        Если вы работаете с SQLite по умолчанию, в начале миграции запускать не нужно: при установке Laravel уже создаёт
        файл database/database.sqlite и сам применяет начальные миграции.
        <br />
        Более подробно миграции будут рассмотрены далее.
    </x-page.page-text>



