    <x-page.page-text>
        По умолчанию Laravel использует SQLite. Это файловая база данных: все данные хранятся
        в одном файле на диске, а не на отдельном сервере. Никакой отдельнойпограммы-сервера
        запускать не нужно - Laravel просточитает и пишет в этот файл.
        <br />
        Для обучения и локальной разработки это очень удобно - не нужно устанавливать и
        настраивать сервер MySQL или PostgreSQL. Проект сразу готов к работе: достаточно
        установить Laravel и можнои зучать миграции, моделиизапросы к базе.
        <br />
        При установке Laravel уже создаёт файл <code>database/database.sqlite</code> и
        применяет начальные миграции, поэтому в начале работы команду migrate запускать не
        нужно.Все служебные таблицы появятся в этом файле автоматически.
        <br />
        В <code>.env</code> это выклядит так:
        <br />
        <code>DB_CONNECTION=sqlite</code>
        <br />
        Для SQLite обычно достаточно строки DB_CONNECTION. Путь к файлу базы Laravel берёт сам - по умолчанию это
        <code>database/database.sqlite</code>. Отдельно прописывать хост, порт и пароль не нужно.
        <br />
        SQLite удобна на этапе обучения, но у неё есть особенности. Например, через PMA
        нельзя просмотреть таблицы SQLite. PMA работает только с MySQL и MariaDB.
        <br />
        Чтобы посмотреть данные SQLite, можно использовать другие инструменты. Популярная программа - DB Browser for
        SQLite: она бесплатная и умеет открывать файл базы напрямую. В VS Code и Cursor есть расширения для работы с
        SQLite прямо в редакторе. Также подойдут универсальные клиенты вроде DBeaver или TablePlus. А через терминал
        можно выполнять запросы командой sqlite3, если она установлена в системе.


