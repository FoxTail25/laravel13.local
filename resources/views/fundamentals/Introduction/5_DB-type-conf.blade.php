    <x-page.page-header>
        Настройки типа базы данных в Laravel
    </x-page.page-header>

    <x-page.page-text>
        Практически любое Laravel-приложение работает с базой данных. В ней хранят пользователей, записи, настройки и
        другие данные проекта. Через базу данных Laravel взаимодействует с миграциями, сидерами и ORM Eloquent.
        <br />
        Хорошая новость в том, что фреймворк не привязан к одному конкретному движку. Laravel умеет работать с разными
        базами, а большую часть кода приложения писать одинаково - независимо от того, SQLite у вас или MySQL.
        <br />
        Настройки работы с БД задают в файле .env в корне проекта. Именно его вы будете править чаще всего. Подробные
        параметры соединений лежат в config/database.php - там описаны все доступные подключения, хосты, порты и другие
        технические детали.
        <br />
        Laravel поддерживает различные движки базы данных: SQLite, MySQL, MariaDB, PostgreSQL, SQL Server. У каждого
        свои особенности: где-то нужен отдельный сервер, где-то достаточно одного файла на диске. На этапе обучения чаще
        всего хватает простого варианта, а на реальном проекте обычно выбирают полноценный сервер баз данных.
        <br />
        Тип базы задаётся строкой DB_CONNECTION в
        <x-page.page-code>
            .env
        </x-page.page-code>
        . Эта настройка говорит Laravel,
        какое подключение из config/database.php использовать. По умолчанию используется SQLite:<br />
        <x-page.page-code>
            DB_CONNECTION=sqlite
        </x-page.page-code>
        Если вы переключитесь на другой движок, в .env появятся дополнительные строки: имя базы, хост, порт, логин и
        пароль. Набор параметров зависит от выбранного типа - у MySQL одни поля, у PostgreSQL другие.
        <br />
        Далее будут подробнее разобраны подключение SQLite, MySQL, MariaDB и PostgreSQL.

    </x-page.page-text>

    <x-page.page-header>
        Возможные проблемы при смене базы данных в Laravel
    </x-page.page-header>
    <x-page.page-text>
        При смене типа базы данных в Laravel могут возникнуть проблемы. Вы меняете значения в <code>.env</code>
        , перезапускаете сервер, а приложение по-прежнему обращается к старой базе или выдаёт ошибку подключения с
        прежними параметрами.
        <br />
        Чаще всего после правки <code>.env</code> Laravel продолжает использовать старые настройки - конфигурация могла
        быть закэширована. Так бывает, если раньше выполняли команду <code>config:cache</code> или проект уже работал на
        боевом сервере.
        <br />
        Чтобы исправить это, очистите кэш:
        <br />
        <code>php artisan config:clear</code>
        <br />
        После этого Laravel снова прочитает актуальные значения из <code>.env</code>
    </x-page.page-text>

